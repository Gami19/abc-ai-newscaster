export function buildUserPrompt(
  input: GenerateScriptInput,
  group: GradeGroup
): string {
  const groupLabel =
    group === "A"
      ? "小学1〜2年生向け（ひらがな中心・短文）"
      : group === "B"
        ? "小学3〜4年生向け（平易な漢字・適度なニュース感）"
        : "小学5〜6年生向け（ニュースの品格を最大化）";

  return `以下の子供の情報をもとに「news おかえり 2035」の原稿を生成してください。

ニックネーム：${input.name}
学年：${input.grade}
将来の夢：${input.dream}
好きなこと：${input.hobby}
がんばっていること：${input.effort}

【重要】
- この原稿を読む子供は${input.grade}です（グループ${group}：${groupLabel}）
- この子供が自分で声に出して読めるように、システムで指定した執筆ルールを必ず守って書いてください
- 好きなこと（${input.hobby}）とがんばっていること（${input.effort}）を④の専門家コメントで必ず伏線回収してください
- プレースホルダー（{name} 等）は原稿に含めない`;
}
