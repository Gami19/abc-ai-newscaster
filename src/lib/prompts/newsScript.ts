import type { GenerateScriptInput, GradeGroup } from "@/types";

const GROUP_A_GRADES = new Set(["小学1年生", "小学2年生"]);
const GROUP_B_GRADES = new Set(["小学3年生", "小学4年生"]);
const GROUP_C_GRADES = new Set(["小学5年生", "小学6年生"]);

export function gradeToGroup(grade: string): GradeGroup {
  if (GROUP_A_GRADES.has(grade)) return "A";
  if (GROUP_B_GRADES.has(grade)) return "B";
  if (GROUP_C_GRADES.has(grade)) return "C";
  console.warn(`[gradeToGroup] unknown grade "${grade}", falling back to B`);
  return "B";
}

